"""Real stdio MCP + Orca smoke test. Generates G-code; does not contact printers."""

import asyncio
import hashlib
import json
import sys
import tomllib
from datetime import UTC, datetime
from pathlib import Path

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def user_state() -> dict[str, str]:
    root = Path.home() / "Library/Application Support/OrcaSlicer"
    paths = [root / "OrcaSlicer.conf", *(root / "user").rglob("*.json")]
    return {str(p): hashlib.sha256(p.read_bytes()).hexdigest() for p in paths if p.is_file()}


async def main() -> None:
    config = tomllib.loads((ROOT / ".codex/config.toml").read_text())["mcp_servers"]["slicer"]
    params = StdioServerParameters(
        command=config["command"], args=config["args"], cwd=config["cwd"], env=config["env"]
    )
    before = user_state()
    report = {"timestamp": datetime.now(UTC).isoformat(), "transport": "stdio", "runs": []}
    async with (
        stdio_client(params) as (reader, writer),
        ClientSession(reader, writer) as session,
    ):
        initialized = await session.initialize()
        report["server"] = initialized.serverInfo.model_dump()
        report["tools"] = [tool.name for tool in (await session.list_tools()).tools]

        async def call(name: str, arguments: dict):
            result = await session.call_tool(name, arguments)
            if result.isError:
                raise RuntimeError(f"{name}: {result.content}")
            return result.structuredContent or json.loads(result.content[0].text)

        report["slicers"] = await call("list_slicers", {})
        analysis = await call("analyze_model", {"model_path": str(ROOT / "examples/cube_20mm.stl")})
        assert analysis["dimensions_mm"] == [20, 20, 20]
        assert abs(analysis["volume_mm3"] - 8000) < 0.01
        report["analysis"] = analysis
        profiles = {}
        choices = {
            "machine": "Bambu Lab X1 Carbon 0.4 nozzle",
            "process": "0.20mm Standard @BBL X1C",
            "filament": "Bambu PLA Basic @BBL X1C",
        }
        for kind, query in choices.items():
            listed = await call("list_profiles", {"kind": kind, "query": query})
            profile = next(
                p
                for p in listed["profiles"]
                if p["name"] == query and p["id"].startswith("builtin:BBL/")
            )
            profiles[f"{kind}_profile"] = profile["id"]
            await call("get_profile", {"profile_id": profile["id"]})
        photo = ROOT / ".slicer-mcp/smoke-photo.png"
        photo.parent.mkdir(exist_ok=True)
        Image.new("RGB", (32, 32), "blue").save(photo)
        context = await session.call_tool(
            "get_model_context",
            {
                "request": {
                    "model_path": str(ROOT / "examples/cube_20mm.stl"),
                    "prompt": "Тестовый куб, проверить настройки",
                    "description": "Synthetic MCP smoke test; image is a test fixture",
                    "photo_paths": [str(photo)],
                    "profile_ids": list(profiles.values()),
                }
            },
        )
        assert not context.isError
        assert any(block.type == "image" for block in context.content)
        report["image_content_verified"] = True
        for label, patch in [
            ("baseline", {}),
            (
                "more_walls",
                {
                    "wall_loops": 4,
                    "sparse_infill_density": 30,
                    "layer_height": 0.16,
                },
            ),
        ]:
            request = {
                "model_path": str(ROOT / "examples/cube_20mm.stl"),
                **profiles,
                "parameters": patch,
            }
            plan = await call("plan_parameters", {"request": request})
            result = await call("slice_model", {"request": request})
            gcode = Path(result["gcode_paths"][0]).read_text()
            assert "; generated by OrcaSlicer" in gcode
            if patch:
                for line in (
                    "; wall_loops = 4",
                    "; sparse_infill_density = 30%",
                    "; layer_height = 0.16",
                ):
                    assert line in gcode, line
            assert result["statistics"]["plate_1.gcode"]["filament used [g]"]
            assert result["statistics"]["plate_1.gcode"]["total estimated time"]
            report["runs"].append({"label": label, "plan": plan, "result": result})
            print(f"{label}: {result['statistics']}", flush=True)
        invalid = await session.call_tool(
            "slice_model",
            {
                "request": {
                    "model_path": str(ROOT / "examples/cube_20mm.stl"),
                    **profiles,
                    "parameters": {"layer_height": 0.8},
                }
            },
        )
        assert invalid.isError
        report["invalid_request_rejected"] = True
    report["user_orca_settings_unchanged"] = before == user_state()
    assert report["user_orca_settings_unchanged"]
    destination = ROOT / ".slicer-mcp/smoke-report.json"
    destination.write_text(json.dumps(report, ensure_ascii=False, indent=2))
    print(f"PASS: {destination}")


if __name__ == "__main__":
    try:
        asyncio.run(main())
    except Exception as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        raise
